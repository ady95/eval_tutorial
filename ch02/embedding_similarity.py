"""02-2 실습: 임베딩 코사인 유사도로 문장 쌍의 의미가 얼마나 가까운지 봅니다.

실행: python -m ch02.embedding_similarity
"""
from ch02.metrics import cosine_similarity
from common.llm import EMBEDDING_MODEL

PAIRS = [
    ("같은 뜻", "대한민국의 수도는 서울입니다.", "한국의 수도는 서울특별시입니다."),
    ("같은 뜻", "환불은 구매 후 7일 이내에 가능합니다.", "물건을 산 날부터 일주일 안에는 돈을 돌려받을 수 있어요."),
    ("단어만", "서울", "대한민국의 수도는 서울입니다."),
    ("다른 뜻", "서울", "부산"),
    ("다른 뜻", "대한민국의 수도는 서울입니다.", "대한민국의 수도는 부산입니다."),
    ("부정문", "환불은 구매 후 7일 이내에 가능합니다.", "환불은 구매 후 7일 이내에 불가능합니다."),
    ("숫자", "환불은 구매 후 7일 이내에 가능합니다.", "환불은 구매 후 30일 이내에 가능합니다."),
    ("무관", "환불은 구매 후 7일 이내에 가능합니다.", "오늘은 날씨가 맑습니다."),
]

print(f"임베딩 모델: {EMBEDDING_MODEL}\n")
print("유사도  구분     문장 A  |  문장 B")
for kind, a, b in PAIRS:
    print(f"{cosine_similarity(a, b):6.3f}  {kind:<6}  {a}  |  {b}")
